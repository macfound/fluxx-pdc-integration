#!/usr/bin/env ruby
# Builds a paste-in script that runs one of the deploy model's actions
# exactly as its button would, without repo access: the method file from
# deploy/installer/, PDC Installer Lib, and the manifest (validate) or install
# bundle (install/uninstall) are embedded.
#
#   ruby deploy/tools/build_one_off_action.rb validate|install|uninstall|restore [OUT]
#       (default OUT: DEV/one-off-<action>.rb)
#
# Paste it into a temporary method on the deploy model and run it on the
# deploy record. It does what the button does (snapshots, changes, results
# fields) and saves the record, so the results show on the form.

require 'json'
require 'zlib'
require 'base64'

ROOT = File.expand_path('../..', __dir__)
# action => [method file, embedded data]
ACTIONS = {
  'validate' => ['PDC Validate Install.rb', 'manifest'],
  'install' => ['PDC Install.rb', 'bundle'],
  'uninstall' => ['PDC Uninstall.rb', 'bundle'],
  'restore' => ['PDC Restore Previous.rb', nil]
}.freeze
action = ARGV[0]
file, data = ACTIONS[action] || abort("usage: build_one_off_action.rb #{ACTIONS.keys.join('|')} [OUT]")
out_path = File.expand_path(ARGV[1] || "DEV/one-off-#{action}.rb", ROOT)

def strip_ruby(src)
  src.lines.reject { |l| l.strip.empty? || l =~ /\A\s*#/ }.join
end

read = lambda { |path| File.read(File.join(ROOT, path), encoding: 'UTF-8') }
lib = strip_ruby(read.call('deploy/installer/PDC Installer Lib.rb'))
body = strip_ruby(read.call("deploy/installer/#{file}"))

script = +"# ONE-OFF PDC #{action.upcase} (generated by deploy/tools/build_one_off_action.rb from deploy/installer/#{file})\n"
script << "# Does what the #{file.sub('PDC ', '').sub('.rb', '')} button does, and saves this record. The last line must be: pdc_result\n"
script << "require 'json'\nrequire 'time'\nrequire 'zlib'\nrequire 'base64'\nrequire 'cgi'\n"
script << "pdc_one_off = true\n"
if data
  json = JSON.generate(JSON.parse(read.call(data == 'manifest' ? 'deploy/pdc-manifest.json' : 'deploy/pdc-install-bundle.json')))
  packed = Base64.strict_encode64(Zlib::Deflate.deflate(json, Zlib::BEST_COMPRESSION))
  script << "pdc_#{data} = JSON.parse(Zlib::Inflate.inflate(Base64.decode64(#{packed.inspect})).force_encoding('UTF-8'))\n"
end
script << lib
script << "pdc_result =\n  begin\n"
script << body.gsub(/^/, '    ')
script << "  rescue => e\n    \"PDC #{action} failed: \#{e.class}: \#{e.message} @ \#{Array(e.backtrace).first(3).join(' | ')}\"\n  end\npdc_result\n"

File.write(out_path, script)
abort 'generated script does not end with pdc_result' unless File.read(out_path).rstrip.end_with?('pdc_result')
puts "Wrote #{out_path} (#{File.size(out_path)} bytes, #{script.lines.size} lines)"
