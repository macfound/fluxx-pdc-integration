#!/usr/bin/env ruby
# Builds a single paste-in export script for an instance that doesn't have
# the installer methods yet (or can't reach the repo). It embeds
# deploy/pdc-scope.json and PDC Installer Lib, so it fetches nothing.
#
#   ruby deploy/tools/build_one_off_export.rb [OUT]   (default DEV/one-off-export.rb)
#
# Paste the output into a temporary method on the deploy model and run it; it
# returns one "PDCEXPORT1:..." line for `pdc_manifest.rb unpack`.
# Comments and blank lines are stripped to keep the paste small.

ROOT = File.expand_path('../..', __dir__)
out_path = File.expand_path(ARGV[0] || 'DEV/one-off-export.rb', ROOT)

def strip_ruby(src)
  src.lines.reject { |l| l.strip.empty? || l =~ /\A\s*#/ }.join
end

require 'json'
scope = JSON.generate(JSON.parse(File.read(File.join(ROOT, 'deploy/pdc-scope.json'), encoding: 'UTF-8')))
lib = strip_ruby(File.read(File.join(ROOT, 'deploy/installer/PDC Installer Lib.rb'), encoding: 'UTF-8'))

extras = <<'RUBY'
extras = {}
safe = lambda do |name, &blk|
  extras[name] = begin
    blk.call
  rescue => e
    "ERROR #{e.class}: #{e.message}"[0, 300]
  end
end
safe.call('deploy_model_stencils') do
  Stencil.where(model_type: model.class.name, deleted_at: nil).map { |s| { 'id' => s.id, 'name' => s.name, 'form_type' => s.form_type, 'json' => s['json'] } }
end
safe.call('deploy_model_states') do
  MachineState.where(model_type: model.class.name, deleted_at: nil).map { |s| { 'name' => s.name, 'state_type' => s.state_type, 'before_validation_enter' => s.unsafe_before_validation_enter } }
end
safe.call('current_user_flags') do
  u = User.find_current_user
  u.attributes.select { |k, _| k =~ /ruby|super|admin|writer|developer|employee|profile/i }
end
safe.call('config_rows_mentioning_pdc') do
  # Exact substrings only; `_` is a LIKE wildcard, so match with INSTR.
  conn = ActiveRecord::Base.connection
  needles = %w[MacModelTypeDynPdc pdc_account_exists pdc_proposal_id]
  trim = lambda { |v| v.is_a?(String) && v.length > 400 ? "#{v[0, 400]}...(#{v.length} chars)" : v }
  out = {}
  %w[user_profile_rules model_field_rules shared_cards model_document_templates role_permissions].each do |t|
    next unless conn.table_exists?(t)
    cols = conn.columns(t).select { |c| [:string, :text].include?(c.type) }.map(&:name)
    next if cols.empty?
    cond = cols.product(needles).map { |c, n| "INSTR(#{conn.quote_column_name(c)}, #{conn.quote(n)}) > 0" }.join(' OR ')
    rows = conn.select_all("SELECT * FROM #{conn.quote_table_name(t)} WHERE #{cond} LIMIT 40").to_a
    out[t] = rows.map { |r| r.each_with_object({}) { |(k, v), h| h[k] = trim.call(v) unless v.nil? } } unless rows.empty?
  end
  out
end
safe.call('pdc_model_rows') do
  # Every column of the PDC model types and their themes, to decide what else is portable.
  types = pdc_scope['owned_model_types'].keys
  { 'machine_model_types' => MachineModelType.where(model_type: types).map(&:attributes),
    'model_themes' => ModelTheme.where(model_type: types).map { |t| t.attributes.reject { |k, _| k =~ /block\z/ } } }
end
safe.call('user_profile_rules_for_pdc') do
  # Profile names alongside ids, so rules can be matched by name on another instance.
  UserProfileRule.where(model_type: pdc_scope['owned_model_types'].keys).map do |r|
    r.attributes.merge('user_profile_name' => (UserProfile.find_by(id: r['user_profile_id'])&.name rescue nil))
  end
end
export_result =
  begin
    lib[:pack_export].call(
      'export_format' => 1,
      'exported_at' => Time.now.utc.iso8601,
      'ref' => 'one-off (embedded scope)',
      'deploy_model' => model.class.name,
      'live' => lib[:collect].call(pdc_scope, true),
      'extras' => extras
    )
  rescue => e
    "PDC export failed: #{e.class}: #{e.message} @ #{Array(e.backtrace).first(3).join(' | ')}"
  end
export_result
RUBY

script = <<~RUBY
  # ONE-OFF PDC EXPORT (generated by deploy/tools/build_one_off_export.rb; read-only)
  # Returns one PDCEXPORT1: line. The last line of this script must be: export_result
  require 'json'
  require 'time'
  pdc_scope = JSON.parse(#{scope.inspect})
RUBY
script << lib << extras

File.write(out_path, script)
abort 'generated script does not end with export_result' unless File.read(out_path).rstrip.end_with?('export_result')
puts "Wrote #{out_path} (#{File.size(out_path)} bytes, #{script.lines.size} lines)"
