#!/usr/bin/env ruby
# Builds a paste-in script that runs only two steps of PDC Bootstrap Deploy
# Model: creating missing attributes and the document type ("# 1.") and the
# deploy model's own form ("# 4."), copied from the bootstrap file so the same code is tested,
# with layout.json and the files it references embedded, so it can be tried
# in Fluxx before anything is pushed.
#
#   ruby deploy/tools/build_one_off_layout.rb [OUT]   (default DEV/one-off-layout.rb)
#
# The generated script overwrites the deploy model's form stencil (dry_run =
# false only) and returns the log.
# In a dry run, attribute creation is rolled back too.

require 'json'
require 'zlib'
require 'base64'

ROOT = File.expand_path('../..', __dir__)
out_path = File.expand_path(ARGV[0] || 'DEV/one-off-layout.rb', ROOT)

boot = File.read(File.join(ROOT, 'deploy/installer/PDC Bootstrap Deploy Model.rb'), encoding: 'UTF-8')
attrs = boot[/^    # 1\. .*?(?=^    # 2\. )/m] or abort 'could not find step 1 in the bootstrap'
step = boot[/^    # 4\. .*?(?=^    # 5\. )/m] or abort 'could not find step 4 in the bootstrap'
step = attrs + step

spec = JSON.parse(File.read(File.join(ROOT, 'deploy/installer/deploy-model.json'), encoding: 'UTF-8'))
files = { spec['stencil_layout'] => File.read(File.join(ROOT, spec['stencil_layout']), encoding: 'UTF-8') }
walk = lambda do |els|
  els.each do |el|
    files[el['text_path']] = File.read(File.join(ROOT, el['text_path']), encoding: 'UTF-8') if el['text_path']
    walk.call(el['elements']) if el['elements']
  end
end
walk.call(JSON.parse(files[spec['stencil_layout']])['elements'])
packed = Base64.strict_encode64(Zlib::Deflate.deflate(JSON.generate(files), Zlib::BEST_COMPRESSION))

script = <<~RUBY
  # ONE-OFF PDC DEPLOY-MODEL LAYOUT (generated by deploy/tools/build_one_off_layout.rb)
  # Runs only the bootstrap's stencil step with the repo files embedded.
  #   dry_run = false   actually overwrite the deploy model's form stencil
  # The last line of this script must be: layout_result
  dry_run = true
  require 'json'
  require 'time'
  require 'zlib'
  require 'base64'
  require 'securerandom'
  pdc_files = JSON.parse(Zlib::Inflate.inflate(Base64.decode64(#{packed.inspect})).force_encoding('UTF-8'))
  spec = JSON.parse(#{JSON.generate(spec).inspect})
  fetch = lambda { |path| pdc_files.fetch(path) }
  mt = model.class.name
  log = []
RUBY
script << <<~'RUBY'
  layout_result =
    begin
      if dry_run
        # Same code, but nothing is saved: the save is rolled back.
        ActiveRecord::Base.transaction(requires_new: true) do
RUBY
script << step.gsub(/^/, '      ')
script << <<~'RUBY'
          raise ActiveRecord::Rollback
        end
      else
RUBY
script << step.gsub(/^/, '    ')
script << <<~'RUBY'
      end
      "PDC layout (#{dry_run ? 'DRY RUN, nothing saved' : 'WRITE'}): #{log.join(' | ')}"
    rescue => e
      "PDC layout failed: #{e.class}: #{e.message} @ #{Array(e.backtrace).first(3).join(' | ')}"
    end
  layout_result
RUBY

File.write(out_path, script)
abort 'generated script does not end with layout_result' unless File.read(out_path).rstrip.end_with?('layout_result')
puts "Wrote #{out_path} (#{File.size(out_path)} bytes, #{script.lines.size} lines, #{files.size} files embedded)"
